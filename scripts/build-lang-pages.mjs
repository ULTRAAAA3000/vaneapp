#!/usr/bin/env node
/**
 * Real, indexable pages in every language: /ru/… and /uk/… next to the English ones.
 *
 * assets/lang.js translates in the browser, which a search engine or an AI assistant that reads the HTML never sees. This script takes
 * every English marketing page that loads lang.js (the list is the sitemap that build-site-pages.mjs just wrote) and writes the
 * Russian and Ukrainian twin with the same dictionaries (scripts/lang-lib.mjs):
 *   - the body, the title, the meta and Open Graph descriptions and the JSON-LD text, translated;
 *   - <html lang>, canonical, og:url and og:locale of that language, and links to the other pages pointing at the same language;
 *   - the same hreflang set on all three versions (en, ru, uk, x-default), so each page and its twins name each other;
 *   - public/sitemap.xml rewritten with the three versions of every page and their alternates.
 * Run through `npm run build:pages`. Do not edit public/ru or public/uk by hand: they are rewritten here.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, rmSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { translateBody, loadDict, norm, getAttr, mapAttrs, tokenize, encodeText, decode } from './lang-lib.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ORIGIN = 'https://vaneapp.dev';
export const LANGS = { en: { locale: 'en_US' }, ru: { locale: 'ru_RU' }, uk: { locale: 'uk_UA' } };
const OTHER = ['ru', 'uk'];

const pub = (p) => join(root, 'public', p);
const urlOf = (path, lang) => ORIGIN + (lang === 'en' ? path : `/${lang}${path === '/' ? '/' : path}`);
const fileOf = (path, lang) => (lang === 'en' ? pub(path === '/' ? 'index.html' : `${path.slice(1)}.html`) : pub(`${lang}/${path === '/' ? 'index.html' : `${path.slice(1)}.html`}`));

// ── which pages: the English ones in the sitemap that load lang.js
const prevSitemap = readFileSync(pub('sitemap.xml'), 'utf8');
const entries = [...prevSitemap.matchAll(/<url><loc>([^<]+)<\/loc>(?:<lastmod>([^<]+)<\/lastmod>)?/g)]
  .map((m) => ({ path: m[1].slice(ORIGIN.length) || '/', lastmod: m[2] }))
  .filter((e) => !/^\/(ru|uk)(\/|$)/.test(e.path));
const localized = entries.filter((e) => existsSync(fileOf(e.path, 'en')) && readFileSync(fileOf(e.path, 'en'), 'utf8').includes('assets/lang.js'));
const localizedPaths = new Set(localized.map((e) => e.path));

// ── clear what an earlier run wrote (only generated pages; llms.txt files stay)
const clear = (dir) => { if (!existsSync(dir)) return; for (const n of readdirSync(dir)) { const p = join(dir, n); if (statSync(p).isDirectory()) { clear(p); if (!readdirSync(p).length) rmSync(p, { recursive: true }); } else if (n.endsWith('.html')) rmSync(p); } };
for (const l of OTHER) clear(pub(l));

// ── the i18n block of the head: hreflang for every version and the og:locale of this one
const block = (path, lang) => {
  const alt = (l) => `<link rel="alternate" hreflang="${l}" href="${urlOf(path, l)}" />`;
  return [
    '<!-- i18n:start (generated by scripts/build-lang-pages.mjs) -->',
    ...Object.keys(LANGS).map(alt),
    `<link rel="alternate" hreflang="x-default" href="${urlOf(path, 'en')}" />`,
    `<meta property="og:locale" content="${LANGS[lang].locale}" />`,
    ...Object.keys(LANGS).filter((l) => l !== lang).map((l) => `<meta property="og:locale:alternate" content="${LANGS[l].locale}" />`),
    '<!-- i18n:end -->',
  ].join('\n  ');
};
const withBlock = (html, path, lang) => {
  const b = block(path, lang);
  if (/<!-- i18n:start[\s\S]*?<!-- i18n:end -->/.test(html)) return html.replace(/<!-- i18n:start[\s\S]*?<!-- i18n:end -->/, () => b);
  if (/<link rel="canonical"[^>]*>/.test(html)) return html.replace(/(<link rel="canonical"[^>]*>)/, (m) => `${m}\n  ${b}`);
  return html.replace('</head>', `  ${b}\n</head>`);
};

const META_KEYS = new Set(['description', 'og:title', 'og:description', 'og:image:alt', 'twitter:title', 'twitter:description', 'twitter:image:alt']);
const report = new Map();   // "ru /pricing" → Set of strings with no entry
const note = (lang, path, s) => { const k = `${lang} ${path}`; if (!report.has(k)) report.set(k, new Set()); report.get(k).add(s); };

function ldWalk(v, tr, ctx) {
  if (Array.isArray(v)) return v.map((x) => ldWalk(x, tr, ctx));
  if (v && typeof v === 'object') {
    const o = {};
    for (const [k, x] of Object.entries(v)) {
      if (k === '@id' || k === '@type' || k === '@context' || k === 'identifier' || k === 'legalName' || k === 'streetAddress' || k === 'postalCode') o[k] = x;
      else if (k === 'url' && typeof x === 'string' && x === ctx.enUrl) o[k] = ctx.url;
      else o[k] = ldWalk(x, tr, ctx);
    }
    if (o['@type'] === 'WebPage' || o['@type'] === 'FAQPage' || o['@type'] === 'SoftwareApplication') o.inLanguage = ctx.lang;
    if (o['@type'] === 'WebPage' && typeof o['@id'] === 'string') o['@id'] = ctx.url + '#page';
    return o;
  }
  if (typeof v === 'string') { const t = tr(v); return t == null ? v : t; }
  return v;
}

function localize(path, lang, dict) {
  let html = readFileSync(fileOf(path, 'en'), 'utf8');
  const tr = (text) => { const k = norm(text); return Object.prototype.hasOwnProperty.call(dict, k) ? dict[k] : null; };
  const url = urlOf(path, lang), enUrl = urlOf(path, 'en');

  // body: text and attributes
  const body = translateBody(html, dict);
  html = body.html;
  for (const s of body.missing.keys()) if (!/^(vane|Slack|Hashnode|curl|Elementor|WooCommerce|Next\.js|React|TypeScript|Shopify|GSAP|Figma)$|^@|^\/ \w+$/i.test(s)) note(lang, path, s);

  // head
  html = html.replace(/<html lang="en"/, `<html lang="${lang}"`);
  html = html.replace(/(<title[^>]*>)([\s\S]*?)(<\/title>)/, (m, a, t, c) => { const r = tr(decode(t)); if (r == null) note(lang, path, `<title> ${norm(t)}`); return a + encodeText(r == null ? decode(t) : r) + c; });
  html = html.replace(/<meta\b[^>]*>/g, (tag) => {
    const key = getAttr(tag, 'name') || getAttr(tag, 'property');
    if (key === 'og:url') return mapAttrs(tag, ['content'], () => url);
    if (!META_KEYS.has(key)) return tag;
    return mapAttrs(tag, ['content'], (_n, v) => { const r = tr(v); if (r == null) note(lang, path, `<meta ${key}> ${norm(v)}`); return r; });
  });
  html = html.replace(/<link rel="canonical"[^>]*>/, (tag) => mapAttrs(tag, ['href'], () => url));
  html = html.replace(/(<script type="application\/ld\+json">)([\s\S]*?)(<\/script>)/g, (m, a, json, c) => {
    const miss = (s) => { if (s.length > 25 && !/^https?:/.test(s)) note(lang, path, `<json-ld> ${s}`); return null; };
    const data = ldWalk(JSON.parse(json), (s) => { const r = tr(s); return r == null ? miss(s) : r; }, { lang, url, enUrl });
    return a + JSON.stringify(data) + c;
  });
  html = withBlock(html, path, lang);

  // links to other localized pages stay in this language; the language buttons say which one is on
  html = tokenize(html).map((tk) => {
    if (tk.t !== 'tag') return tk.s;
    if (/^<a\s/i.test(tk.s)) {
      return mapAttrs(tk.s, ['href'], (_n, v) => {
        const m = /^(\/[^?#]*)?([?#].*)?$/.exec(v);
        if (!m || !v.startsWith('/') || v.startsWith('//')) return null;
        const p = m[1] || '/';
        return localizedPaths.has(p) ? `${urlOf(p, lang).slice(ORIGIN.length)}${m[2] || ''}` : null;
      });
    }
    const dl = getAttr(tk.s, 'data-lang');
    if (dl && /^<button\s/i.test(tk.s)) return mapAttrs(tk.s, ['aria-pressed'], () => String(dl === lang));
    return tk.s;
  }).join('');
  return html;
}

// ── write: English pages get the i18n block, the twins are generated from them
const dicts = Object.fromEntries(OTHER.map((l) => [l, loadDict(root, l)]));
for (const { path } of localized) {
  const f = fileOf(path, 'en');
  writeFileSync(f, withBlock(readFileSync(f, 'utf8'), path, 'en'));
}
for (const l of OTHER) {
  for (const { path } of localized) {
    const f = fileOf(path, l);
    mkdirSync(dirname(f), { recursive: true });
    writeFileSync(f, localize(path, l, dicts[l]));
  }
}

// ── the sitemap: every version of every page, each with its alternates
const alt = (path) => ['en', ...OTHER].map((l) => `<xhtml:link rel="alternate" hreflang="${l}" href="${urlOf(path, l)}"/>`).concat(`<xhtml:link rel="alternate" hreflang="x-default" href="${urlOf(path, 'en')}"/>`).join('');
const rows = [];
for (const e of entries) {
  const lm = e.lastmod ? `<lastmod>${e.lastmod}</lastmod>` : '';
  if (!localizedPaths.has(e.path)) { rows.push(`  <url><loc>${urlOf(e.path, 'en')}</loc>${lm}</url>`); continue; }
  for (const l of ['en', ...OTHER]) rows.push(`  <url><loc>${urlOf(e.path, l)}</loc>${lm}${alt(e.path)}</url>`);
}
writeFileSync(pub('sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${rows.join('\n')}\n</urlset>\n`);

console.log(`wrote ${localized.length * OTHER.length} pages (${OTHER.join(', ')}) for ${localized.length} English pages and public/sitemap.xml`);
if (process.env.LANG_MISSING_JSON) writeFileSync(process.env.LANG_MISSING_JSON, JSON.stringify([...new Set([...report.values()].flatMap((x) => [...x]).map((x) => x.replace(/^<[^>]+> /, '')))], null, 1));
if (report.size) {
  console.log('\nNo dictionary entry (add to assets/lang-ru.js and lang-uk.js, or ignore if it is a name):');
  for (const [k, set] of report) console.log(`  ${k}: ${[...set].slice(0, 6).join(' | ')}${set.size > 6 ? ` … +${set.size - 6}` : ''}`);
}
